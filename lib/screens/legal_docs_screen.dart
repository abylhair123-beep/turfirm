import 'package:flutter/material.dart';
import '../theme/app_colors.dart';
import '../theme/app_text_styles.dart';

enum LegalDocType {
  offer,
  refund,
  privacy,
  aviation,
}

class LegalDocsScreen extends StatefulWidget {
  final LegalDocType initialDoc;

  const LegalDocsScreen({
    super.key,
    this.initialDoc = LegalDocType.offer,
  });

  @override
  State<LegalDocsScreen> createState() => _LegalDocsScreenState();
}

class _LegalDocsScreenState extends State<LegalDocsScreen> with SingleTickerProviderStateMixin {
  late TabController _tabController;

  @override
  void initState() {
    super.initState();
    final initialIndex = switch (widget.initialDoc) {
      LegalDocType.offer => 0,
      LegalDocType.refund => 1,
      LegalDocType.privacy => 2,
      LegalDocType.aviation => 3,
    };
    _tabController = TabController(length: 4, vsync: this, initialIndex: initialIndex);
  }

  @override
  void dispose() {
    _tabController.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: AppColors.bg,
      appBar: AppBar(
        backgroundColor: Colors.white,
        elevation: 0,
        surfaceTintColor: Colors.transparent,
        leading: IconButton(
          icon: const Icon(Icons.arrow_back_ios_new_rounded, color: AppColors.ink, size: 20),
          onPressed: () => Navigator.of(context).pop(),
        ),
        title: Text(
          'Правовая информация & Оферта',
          style: AppText.sora(size: 16, weight: FontWeight.w700, color: AppColors.ink),
        ),
        bottom: TabBar(
          controller: _tabController,
          isScrollable: true,
          tabAlignment: TabAlignment.start,
          labelColor: AppColors.teal,
          unselectedLabelColor: AppColors.muted,
          indicatorColor: AppColors.teal,
          indicatorWeight: 3,
          labelStyle: AppText.work(size: 12.5, weight: FontWeight.w700),
          unselectedLabelStyle: AppText.work(size: 12.5, weight: FontWeight.w500),
          tabs: const [
            Tab(text: 'Публичная оферта'),
            Tab(text: 'Возврат & Аннуляция (ФПР)'),
            Tab(text: 'Согласие на сбор и передачу ПДН'),
            Tab(text: 'Авиаперевозка & Туркод'),
          ],
        ),
      ),
      body: TabBarView(
        controller: _tabController,
        children: const [
          _PublicOfferTab(),
          _RefundPolicyTab(),
          _PrivacyPolicyTab(),
          _AviationRulesTab(),
        ],
      ),
    );
  }
}

